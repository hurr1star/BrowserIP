// Generates lib/messages-en.js (the English fallback used outside the
// browser, e.g. in tests) from _locales/en/messages.json, the source of truth.
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

const root = new URL("..", import.meta.url);
export const GENERATED_PATH = new URL("lib/messages-en.js", root);

export function renderMessagesModule() {
  const messages = JSON.parse(readFileSync(new URL("_locales/en/messages.json", root), "utf8"));
  const entries = Object.entries(messages).map(([key, { message }]) => `  ${key}: ${JSON.stringify(message)}`);
  return `// Generated by scripts/build-locales.js from _locales/en/messages.json. Do not edit.\nexport const MESSAGES_EN = {\n${entries.join(",\n")}\n};\n`;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  writeFileSync(GENERATED_PATH, renderMessagesModule());
  console.log(`wrote ${fileURLToPath(GENERATED_PATH)}`);
}
